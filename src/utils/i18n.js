export function useLocale() {
  const [locale, setLocale] = useState(getSavedLocale());

  useEffect(() => {
    saveLocale(locale);
  }, [locale]);

  const t = (key, fallback = key) => translations[locale]?.[key] || translations.en[key] || fallback;

  return { locale, setLocale, t };
}
